 Q15. Find the top-performing product category for each month based on revenue

SELECT 
    month,
    product_category,
    total_revenue
FROM (
    SELECT 
        DATE_TRUNC('month', order_date) AS month,
        product_category,
        SUM(revenue) AS total_revenue,
        RANK() OVER (
            PARTITION BY DATE_TRUNC('month', order_date) 
            ORDER BY SUM(revenue) DESC
        ) AS rank
    FROM shopify_sales
    GROUP BY month, product_category
) t
WHERE rank = 1
ORDER BY month;

