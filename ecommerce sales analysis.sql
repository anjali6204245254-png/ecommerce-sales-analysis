DATABASE shopify_sales

CREATE TABLE shopify_sales (
    order_id TEXT,
    order_date DATE,
    customer_id TEXT,
    product_id TEXT,
    product_category TEXT,
    product_price NUMERIC,
    discount_percent NUMERIC,
    quantity INT,
    customer_country TEXT,
    traffic_source TEXT,
    payment_method TEXT,
    shipping_cost NUMERIC,
    rating NUMERIC,
    is_returned INT,
    discounted_price NUMERIC,
    revenue NUMERIC,
    profit NUMERIC
);
