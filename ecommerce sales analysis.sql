Q7.Classify customers into High, Medium,and Low value based on total spending.

SELECT 
    customer_segment,
    COUNT(*) AS total_customers
FROM (
    SELECT 
        customer_id,
        CASE 
            WHEN SUM(revenue) > 10000 THEN 'High Value'
            WHEN SUM(revenue) BETWEEN 5000 AND 10000 THEN 'Medium Value'
            ELSE 'Low Value'
        END AS customer_segment
    FROM shopify_sales
    GROUP BY customer_id
) t
GROUP BY customer_segment;

Result:
   Customer_Segment    Total Customer   
  High Value             15
  Medium Value           29751
  Low Value              1388

 Insight:
 Customers are segmented based on their spending behavior. High-value customers 
 contribute the most to revenue and should be prioritized for retention strategies, 
 while medium and low-value customers offer opportunities for upselling and engagement.

